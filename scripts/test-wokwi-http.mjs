import assert from "node:assert/strict";
import fs from "node:fs";
const base="http://localhost:3000", proxy="http://127.0.0.1:8787";
const header={"Content-Type":"application/json","Authorization":`Bearer ${process.env.WOKWI_INGEST_TOKEN}`};
const files=["shelter","classroom"].flatMap(id=>[`work/wokwi/history-${id}.json`,`work/wokwi/config-${id}.json`]);
const previous=files.map(p=>fs.existsSync(p)?fs.readFileSync(p):null);
const report=[];
const sample={device_id:"climate-shelter-esp32",location_id:"shelter",message_id:crypto.randomUUID(),temperature:29,humidity:65,co2:800,pm25:20,pcm_temperature:27,light_lux:500,occupancy:false,sensor_ok:true,tank_ok:true,fan_on:true,pump_on:true,hvac_on:false,ventilation_degrees:0,setpoint:26.7,firmware_version:"climate-wokwi-3.0"};
const classroom={...sample,device_id:"climate-classroom-esp32",location_id:"classroom",message_id:crypto.randomUUID(),temperature:32,occupancy:true,hvac_on:true,ventilation_degrees:90};
try {
  for(const path of ["/","/dashboard","/api/auth/login","/api/wokwi/live"]){assert.equal((await fetch(proxy+path)).status,404);}
  assert.equal((await fetch(proxy+"/telemetry",{method:"POST",body:"{}"})).status,401);
  assert.equal((await fetch(proxy+"/telemetry",{method:"POST",headers:header,body:JSON.stringify({...sample,tank_ok:false})})).status,400);
  report.push("Proxy exposes only authenticated POST /telemetry; invalid interlock rejected.");
  const send=(p=sample)=>fetch(proxy+"/telemetry",{method:"POST",headers:header,body:JSON.stringify(p)});
  assert.equal((await send({...sample,location_id:"classroom"})).status,400);
  assert.equal((await send({...sample,hvac_on:true})).status,400);
  assert.equal((await send({...sample,ventilation_degrees:90})).status,400);
  assert.equal((await send()).status,200); assert.equal((await send()).status,200);
  assert.equal((await send(classroom)).status,200);
  const live=await (await fetch(base+"/api/wokwi/live")).json();
  assert.equal(live.history.filter(s=>s.message_id===sample.message_id).length,1);
  assert.equal(live.history.some(s=>s.message_id===classroom.message_id),false);
  const roomLive=await (await fetch(base+"/api/wokwi/live?location=classroom")).json();
  assert.equal(roomLive.latest.temperature,32);
  assert.equal(roomLive.history.some(s=>s.message_id===sample.message_id),false);
  assert.equal((await fetch(base+"/api/wokwi/live?location=unknown")).status,400);
  report.push("Valid telemetry returns HTTP 200; message retries deduplicate.");
  const publicRows=await (await fetch(base+"/api/public")).json();
  assert.equal(publicRows.length,1);
  assert.equal(publicRows[0].school.name,"SD Negeri Candigaron 01");
  assert.equal(publicRows[0].latest.temperature,29);
  assert.equal(publicRows[0].wokwi.latest.message_id,sample.message_id);
  assert.equal(publicRows[0].demo,false);
  assert.equal(publicRows[0].history.at(-1).recorded_at,live.latest.received_at);
  assert.equal(publicRows[0].latest.energy_consumption,null);
  assert.equal(publicRows[0].locations.length,2);
  assert.equal(publicRows[0].locations.find(l=>l.location.id==="shelter").latest.temperature,29);
  assert.equal(publicRows[0].locations.find(l=>l.location.id==="classroom").latest.temperature,32);
  report.push("One Candigaron school contains two isolated locations, histories and device identities; shelter refuses HVAC/ventilation.");
  const login=await fetch(base+"/api/auth/login",{method:"POST",headers:{"Content-Type":"application/json",Origin:base},body:JSON.stringify({demoRole:"admin"})});
  assert.equal(login.status,200);
  const cookie=login.headers.get("set-cookie").split(";")[0];
  const dashboard=await (await fetch(base+"/api/dashboard",{headers:{Cookie:cookie}})).json();
  assert.equal(dashboard.wokwi.latest.message_id,sample.message_id);
  assert.equal(dashboard.devices.find(d=>d.kind==="pump").value,100);
  assert.equal(dashboard.sensors.filter(s=>s.zone_id==="20000000-0000-4000-8000-000000000002").at(-1).temperature,29);
  assert.equal(dashboard.sensors.filter(s=>s.zone_id==="20000000-0000-4000-8000-000000000004").at(-1).temperature,32);
  const managed=dashboard.devices.filter(d=>d.firmware_version==="climate-wokwi-3.0" && d.kind!=="sensor");
  assert.equal(managed.filter(d=>d.zone_id.endsWith("000000000002")).length,2);
  assert.equal(managed.filter(d=>d.zone_id.endsWith("000000000004")).length,4);
  assert.equal(dashboard.devices.filter(d=>d.zone_id.endsWith("000000000002") && d.kind!=="sensor").length,2);
  assert.equal(dashboard.devices.filter(d=>d.zone_id.endsWith("000000000004") && d.kind!=="sensor").length,4);
  const config=await fetch(base+"/api/wokwi/config",{method:"POST",headers:{"Content-Type":"application/json",Origin:base,Cookie:cookie},body:JSON.stringify({location_id:"shelter",setpoint:27.5})});
  assert.equal(config.status,200); assert.equal((await (await send()).json()).setpoint,27.5);
  assert.equal((await (await send(classroom)).json()).setpoint,roomLive.requestedSetpoint);
  const roomConfig=await fetch(base+"/api/wokwi/config",{method:"POST",headers:{"Content-Type":"application/json",Origin:base,Cookie:cookie},body:JSON.stringify({location_id:"classroom",setpoint:30})});
  assert.equal(roomConfig.status,200);
  assert.equal((await (await send(classroom)).json()).setpoint,30);
  assert.equal((await (await send()).json()).setpoint,27.5);
  assert.equal((await fetch(base+"/api/wokwi/config",{method:"POST",headers:{"Content-Type":"application/json",Origin:"https://invalid.example",Cookie:cookie},body:JSON.stringify({location_id:"shelter",setpoint:25})})).status,403);
  await fetch(base+"/api/auth/logout",{method:"POST",headers:{"Content-Type":"application/json",Origin:base,Cookie:cookie},body:"{}"});
  report.push("Dashboard has 2 shelter and 4 classroom actuators. Setpoints return only to their own device; wrong origin denied.");
  console.log(report.join("\n"));
  fs.writeFileSync("work/wokwi-http-verification.json",JSON.stringify({at:new Date().toISOString(),source:"HTTP test fixture (not Wokwi simulator)",checks:report},null,2));
} finally {
  files.forEach((p,i)=>{if(previous[i])fs.writeFileSync(p,previous[i]);else if(fs.existsSync(p))fs.unlinkSync(p);});
}
